/**
 * Get authentic, exact medical device image by name
 */
export const getExactMedicalImage = (name = '', fallbackUrl = '') => {
  if (fallbackUrl && typeof fallbackUrl === 'string' && fallbackUrl.trim() !== '') {
    return fallbackUrl;
  }
  const cleanName = (name || '').toLowerCase().trim();
  for (const [key, url] of Object.entries(MEDICAL_EQUIPMENT_IMAGES)) {
    if (cleanName.includes(key)) {
      return url;
    }
  }
  return MEDICAL_EQUIPMENT_IMAGES['wheelchair'];
};

/**
 * Handle image loading error without substituting unrelated equipment images
 */
export const handleImageError = (e, equipmentName = '') => {
  const exactUrl = getExactMedicalImage(equipmentName);
  if (e.target.src !== exactUrl) {
    e.target.src = exactUrl;
  }
};

